CLASSIFICATION_RULES = """
分类逻辑：
1. 将公司名称和经营范围拼接后，与各类型的关键词进行匹配
2. 匹配到任意一个关键词，即将该类型加入结果列表
3. 支持多选判断：一个公司可以同时属于多种类型
4. 如果没有匹配到任何类型，默认使用 "fundamental"（基本面分析）

优先级说明：
- 周期股(cyclical)和红利股(dividend)优先级较高，通常二选一
- 成长股(growth)、价值股(value)、防御股(defensive)可与前者共存
- 例如：
  - "煤炭开采" -> ["cyclical"]
  - "电力公司" -> ["dividend", "value"]
  - "白酒企业" -> ["dividend", "defensive"]

修改建议：
- 如需更精确的分类，可增加行业专属关键词
- 如需调整优先级，可修改匹配顺序或在STOCK_TYPE_KEYWORDS中增删关键词
- 建议保持多选特性，以便从多角度分析公司
"""


# =============================================================================
# 辅助函数
# =============================================================================

def get_keywords_for_type(stock_type: str) -> list:
    """获取指定类型的关键词列表"""
    return STOCK_TYPE_KEYWORDS.get(stock_type, [])


def get_all_keywords() -> dict:
    """获取所有类型的关键词（用于调试）"""
    return STOCK_TYPE_KEYWORDS.copy()


def add_keywords(stock_type: str, keywords: list) -> None:
    """
    动态添加关键词（运行时修改）

    Args:
        stock_type: 股票类型
        keywords: 关键词列表
    """
    if stock_type in STOCK_TYPE_KEYWORDS:
        STOCK_TYPE_KEYWORDS[stock_type].extend(keywords)
        # 去重
        STOCK_TYPE_KEYWORDS[stock_type] = list(set(STOCK_TYPE_KEYWORDS[stock_type]))
    else:
        STOCK_TYPE_KEYWORDS[stock_type] = keywords


def classify_by_keywords(text: str) -> list:
    """
    根据文本内容判断股票类型

    Args:
        text: 公司名称和经营范围的组合文本

    Returns:
        匹配的股票类型列表
    """
    if not text:
        return ["fundamental"]

    text_lower = text.lower()
    matched_types = []

    for stock_type, keywords in STOCK_TYPE_KEYWORDS.items():
        for keyword in keywords:
            if keyword.lower() in text_lower:
                matched_types.append(stock_type)
                break

    if not matched_types:
        matched_types.append("fundamental")

    return list(set(matched_types))


